"""Render the LLMCuisine-22 datasheet (Gebru et al. 2021) with every number computed from the release.

Inputs: data/release/LLMCuisine-22/{MANIFEST.json, calls.csv, coverage.csv, generation_log.jsonl.gz},
configs/models.yaml, data/generated/spend_ledger.json. Output: docs/datasheet_LLMCuisine-22.md (and a copy in the
release folder). Usage (repo root, after generation/build_release.py): .venv/bin/python generation/write_datasheet.py
"""

from __future__ import annotations

import gzip
import json
import shutil
from collections import defaultdict
from pathlib import Path

import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[1]
REL = REPO / "data" / "release" / "LLMCuisine-22"
OUT = REPO / "docs" / "datasheet_LLMCuisine-22.md"


def log_facts() -> pd.DataFrame:
    """Per model: id/revision/engine, sampling, first and last call date, token totals."""
    facts: dict[str, dict] = defaultdict(lambda: {"dates": [], "in": 0, "out": 0})
    with gzip.open(REL / "generation_log.jsonl.gz", "rt", encoding="utf-8") as fh:
        for line in fh:
            r = json.loads(line)
            f = facts[r["model_key"]]
            f["id"] = r.get("canonical_id") or r.get("model_id") or r.get("hf_id")
            f["revision"] = r.get("revision") or r.get("model_version_returned") or ""
            f["engine"] = r.get("engine") or r.get("provider") or r.get("runner_version") or ""
            f["params"] = r.get("sampling") or r.get("params_sent") or {}
            f["dates"].append(r.get("batch_started_utc") or r.get("started_utc") or r.get("submitted_utc") or "")
            f["in"] += int(r.get("n_prompt_tokens") or 0)
            f["out"] += int(r.get("n_output_tokens") or 0)
    rows = []
    for m, f in sorted(facts.items()):
        dates = sorted(d for d in f["dates"] if d)
        rows.append(
            {
                "model": m,
                "model id": f["id"],
                "revision / version": str(f["revision"])[:16],
                "engine": f["engine"],
                "decoding": json.dumps(f["params"], sort_keys=True),
                "generated (UTC)": f"{dates[0][:10]} to {dates[-1][:10]}" if dates else "",
                "tokens in / out": f"{f['in']:,} / {f['out']:,}",
            }
        )
    return pd.DataFrame(rows)


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(out)


def main() -> int:
    man = json.loads((REL / "MANIFEST.json").read_text())
    calls = pd.read_csv(REL / "calls.csv")
    cov = pd.read_csv(REL / "coverage.csv")
    models_cfg = yaml.safe_load((REPO / "configs" / "models.yaml").read_text())["models"]
    ledger = json.loads((REPO / "data" / "generated" / "spend_ledger.json").read_text())
    spend = sum(e.get("actual_usd", 0) for e in ledger)
    per_model = (
        calls.groupby("model_key")
        .agg(
            calls=("call_id", "size"),
            recipes=("n_recipes", "sum"),
            exactly_5=("n_recipes", lambda s: f"{(s == 5).mean():.1%}"),
            parse_ok=("parse_status", lambda s: f"{(s == 'ok').mean():.1%}"),
            repaired=("parse_status", lambda s: f"{(s == 'repaired').mean():.1%}"),
            salvaged=("parse_status", lambda s: f"{(s == 'salvaged').mean():.1%}"),
        )
        .reset_index()
        .rename(columns={"model_key": "model"})
    )
    share_cols = [c for c in cov.columns if c.startswith("share_")]

    def weighted_shares(g: pd.DataFrame) -> pd.Series:
        return pd.Series(
            {c.replace("share_", ""): f"{(g[c] * g['lines']).sum() / g['lines'].sum():.1%}" for c in share_cols}
        )

    cov_tab = (
        cov.groupby("model_key")
        .apply(weighted_shares, include_groups=False)
        .reset_index()
        .rename(columns={"model_key": "model"})
    )
    licences = pd.DataFrame(
        [{"model": m, "licence / terms": models_cfg.get(m, {}).get("license", "")} for m in per_model["model"]]
    )
    facts = log_facts()
    c = man["counts"]
    text = f"""# Datasheet: LLMCuisine-22

Generated by `generation/write_datasheet.py` from the release files; every number below is computed. Format:
Gebru et al. (2021), *Datasheets for Datasets*. Release manifest: `data/release/LLMCuisine-22/MANIFEST.json`.

## Motivation
- **Purpose.** To test whether large language models reproduce the measurable culinary fingerprints of world
  cuisines (food pairing, flavor drivers, category fingerprints, ingredient popularity) when asked for traditional
  recipes. It is deliverable D1 of the project *Do AI Chefs Respect Culinary Fingerprints?*
- **Creators.** Group 44 (roll nos. 2023355, 2023477), BIO544 Computational Gastronomy, IIIT-Delhi, Monsoon 2026.
  The instructor was Prof. Ganesh Bagler.
- **Funding.** None; a course project. The only API spend was ${spend:.2f} in total (OpenAI Batch).

## Composition
- **Instances.** {c["recipes"]:,} recipes (title, ingredient lines with quantities, ordered instructions) from
  {c["calls"]:,} logged calls, with {c["ingredient_lines"]:,} ingredient lines aliased to CulinaryDB entities.
- **Design.** 22 CulinaryDB regions × 2 prompt conditions (plain; home-cook persona with 8 places per region, each
  used equally often) × 16 replicates × 5 recipes per call = 3,520 recipes per model.
- **Models and their recipes:**

{md_table(per_model)}

- **Missing data.** Some calls return fewer than 5 recipes. This is kept as data (the instruction-following
  shortfall itself is measured), and only the first 5 recipes of any call are released.
- **Aliasing coverage** (share of ingredient lines by match type: full, partial, curated, none):

{md_table(cov_tab)}

- **Relationship to CulinaryDB.** The files follow CulinaryDB's format and entity IDs (Singh & Bagler 2018), so
  every CulinaryDB analysis applies unchanged.
- **Sensitive content.** None by design: no personal data is involved, the prompts ask only for recipes, and the
  persona prompt names a country or region only.

## Collection process
- **Prompts.** Frozen prompt set v1, sha256 `{man["prompt_set"]["sha256"][:16]}…`, in `configs/prompts/v1/`. The
  prompts never mention flavor pairing.
- **Models, versions and decoding:**

{md_table(facts)}

- **Decoding policy.** Pre-registered; see `configs/models.yaml`.
  - Open-weight models: T 0.7, top_p 0.95, thinking off, max 6,144 tokens.
  - APIs: provider defaults at the lowest reasoning or thinking level.
  - Per-call seed: sha256 of the model and prompt key.
- **Infrastructure.**
  - Open-weight models ran on Kaggle GPUs (T4 ×2) with vLLM or Hugging Face transformers; the engine is logged per call.
  - Gemini used the free API, and GPT-6-Luna the OpenAI Batch API.
  - Every call is logged in `generation_log.jsonl.gz`.

## Preprocessing, cleaning and labelling
- **Parsing** (`generation/common.py`):
  - JSON extraction with structural repairs only: trailing commas, bracket balancing, recipe-boundary normalisation,
    and reading a stream of JSON values;
  - then salvage of complete recipe objects;
  - recipe text is never edited, and the status of every call is in `calls.csv`.
- **Aliasing.** The ingredient lines are mapped by our implementation of the CulinaryDB protocol
  (`flavoraudit.aliasing`). On held-out CulinaryDB expert mappings it agrees on 97.9% of unique lines and 99.0% of
  line occurrences. Reviewed curation decisions are in `curation/alias_overrides.csv`.
- **Raw data.** The unparsed raw outputs are kept in the generation log.

## Uses
- **Intended uses.** Auditing and benchmarking how LLMs represent cuisines; food-pairing research; teaching.
- **Not intended for:**
  - nutrition, allergy or food-safety decisions;
  - presenting generated recipes as authentic or tested. The recipes were not cooked or checked by people.

## Distribution
- **Licence.** CC BY-NC-SA 4.0 (`DATA_LICENSE.md`), with attribution to CulinaryDB and FlavorDB (CC BY-NC-SA 3.0).
- **LLM output terms:**

{md_table(licences)}

- **Venues.** Kaggle, Hugging Face Datasets and Zenodo, after the team's approval.

## Maintenance
- Maintained by Group 44. Issues go to the project repository.
- Versions follow the prompt-set and release manifests, and the files carry sha256 checksums.
"""
    OUT.write_text(text, encoding="utf-8")
    shutil.copy(OUT, REL / "DATASHEET.md")
    print(f"wrote {OUT.relative_to(REPO)} and {(REL / 'DATASHEET.md').relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
