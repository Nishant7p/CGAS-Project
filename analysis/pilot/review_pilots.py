"""Review pilot generations before freezing the prompts (Phase 4, step 6).

For each model it reports: parse rate, recipes per call, ingredient lines per recipe, aliasing coverage (share of
ingredient lines mapped to a CulinaryDB entity, and how they matched), title duplicates, and the most frequent
unmatched words. Writes data/interim/pilot/{pilot_lines.parquet, review.md}.

Usage (repo root): .venv/bin/python analysis/pilot/review_pilots.py
"""

from __future__ import annotations

import subprocess
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

from flavoraudit.aliasing import Aliaser, tokens
from flavoraudit.data import load_culinarydb

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "data" / "interim" / "pilot"


def main() -> int:
    subprocess.run([sys.executable, str(REPO / "generation" / "parse_outputs.py")], check=True, capture_output=True)
    calls = pd.read_parquet(REPO / "data" / "generated" / "parsed" / "calls.parquet")
    recipes = pd.read_parquet(REPO / "data" / "generated" / "parsed" / "recipes.parquet")
    cdb = load_culinarydb()
    al = Aliaser.reference(cdb)
    names = dict(zip(cdb.ingredients["entity_id"], cdb.ingredients["name"], strict=True))
    rows = []
    for r in recipes.itertuples():
        for line in r.ingredients:
            m = al.alias(line)
            rows.append(
                {
                    "model_key": r.model_key,
                    "region_code": r.region_code,
                    "condition": r.condition,
                    "recipe_uid": r.recipe_uid,
                    "line": line,
                    "entity_id": m.entity_id,
                    "entity": names.get(m.entity_id),
                    "how": m.how,
                }
            )
    lines = pd.DataFrame(rows)
    OUT.mkdir(parents=True, exist_ok=True)
    lines.to_parquet(OUT / "pilot_lines.parquet", index=False)
    report = [
        "# Pilot review",
        "",
        f"Generated by `analysis/pilot/review_pilots.py`. Calls: {len(calls)}, recipes: {len(recipes)}.",
        "",
    ]
    summary = []
    for mk, c in calls.groupby("model_key"):
        rec = recipes[recipes["model_key"] == mk]
        ln = lines[lines["model_key"] == mk]
        dup = rec["title"].str.lower().str.strip().duplicated().mean() if len(rec) else 0
        summary.append(
            {
                "model": mk,
                "calls": len(c),
                "parsed_ok": f"{c['parse_status'].isin(['ok', 'repaired', 'salvaged']).mean():.0%}",
                "calls_with_5": f"{(c['n_recipes'] == 5).mean():.0%}",
                "recipes": len(rec),
                "lines/recipe": round(rec["n_ingredient_lines"].mean(), 1) if len(rec) else 0,
                "aliased_full": f"{(ln['how'] == 'full').mean():.1%}",
                "aliased_partial": f"{(ln['how'] == 'partial').mean():.1%}",
                "unmatched": f"{(ln['how'] == 'none').mean():.1%}",
                "dup_titles": f"{dup:.1%}",
                "mean_out_tokens": int(c["n_output_tokens"].mean()) if c["n_output_tokens"].notna().any() else None,
            }
        )
    sm = pd.DataFrame(summary)
    print(sm.to_string(index=False))
    report += ["## Per-model summary", "", "| " + " | ".join(sm.columns) + " |", "|" + "---|" * len(sm.columns)]
    report += ["| " + " | ".join(str(v) for v in row) + " |" for row in sm.itertuples(index=False)]
    unmatched = lines[lines["how"] == "none"]
    words = Counter(w for t in unmatched["line"] for w in tokens(t))
    report += [
        "",
        "## Most frequent words in unmatched lines (all models)",
        "",
        ", ".join(f"{w} ({c})" for w, c in words.most_common(40)),
    ]
    report += ["", "## Example unmatched lines", ""] + [f"- {x}" for x in unmatched["line"].drop_duplicates().head(25)]
    partial = lines[lines["how"] == "partial"]
    report += ["", "## Example partial matches (line -> entity)", ""]
    report += [f"- {a} -> {b}" for a, b in partial[["line", "entity"]].drop_duplicates().head(25).to_numpy()]
    (OUT / "review.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print(f"\nunmatched words: {words.most_common(25)}")
    print(f"wrote {(OUT / 'review.md').relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
